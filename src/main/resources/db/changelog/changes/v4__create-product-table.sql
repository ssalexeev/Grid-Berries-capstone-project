CREATE TABLE IF NOT EXISTS product (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    seller_profile_id bigint NOT NULL,
    title varchar(100) NOT NULL,
    description text,
    price decimal(10, 2) NOT NULL CHECK (price >= 0),
    stock_quantity int NOT NULL DEFAULT 0 CHECK (stock_quantity >= 0),
    image_url varchar(255),
    status varchar(50) NOT NULL,
    created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_product_on_seller_profile
        FOREIGN KEY (seller_profile_id) REFERENCES seller_profile(id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_product_seller_profile ON product(seller_profile_id);
